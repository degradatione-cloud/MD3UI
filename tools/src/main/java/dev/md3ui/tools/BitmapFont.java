    private static void put(char c, int w, String hex) {
        byte[] rows = new byte[HEIGHT];
        for (int i = 0; i < HEIGHT; i++) {
            rows[i] = (byte) Integer.parseInt(hex.substring(i * 2, i * 2 + 2), 16);
        }
        GLYPHS.put(c, rows);
        WIDTHS.put(c, w);
    }

